package sql

import (
	"fmt"
	"wiki-kernel/av"
	"wiki-kernel/internal/avrender"
	"wiki-kernel/util"
)

func RenderAttributeViewTable(attrView *av.AttributeView, view *av.View, query string, depth *int, cachedAttrViews map[string]*av.AttributeView) *av.Table {
	ret, _ := avrender.Table(attrView, view, query, avrender.Environment{
		RemoveMissingField: func(a *av.AttributeView, v *av.View, id string) error { removeMissingField(a, v, id); return nil },
		FilterItems:        func(items map[string][]*av.KeyValues) error { filterNotFoundAttrViewItems(items); return nil },
		BlockAttrs:         func(ids []string) (map[string]map[string]string, error) { return BatchGetBlockAttrs(ids), nil },
		AutoValues: func(a *av.AttributeView, c av.Collection, ials map[string]map[string]string) error {
			fillAttributeViewAutoGeneratedValues(a, c, ials, depth, cachedAttrViews)
			return nil
		},
		Templates: func(a *av.AttributeView, v *av.View, c av.Collection, ials map[string]map[string]string) error {
			err := fillAttributeViewTemplateValues(a, v, c, ials)
			if err != nil {
				util.PushErrMsg(fmt.Sprintf(util.Langs[util.Lang][44], util.EscapeHTML(err.Error())), 30000)
			}
			return nil
		},
	})
	return ret
}
