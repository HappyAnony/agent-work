func legacyAVRenderEnvironment(depth *int, cached map[string]*av.AttributeView) avrender.Environment {
	var boundTrees map[string]*parse.Tree
	return avrender.Environment{
		RemoveMissingField: func(a *av.AttributeView, v *av.View, id string) error { removeMissingField(a, v, id); return nil },
		FilterItems:        func(items map[string][]*av.KeyValues) error { filterNotFoundAttrViewItems(items); return nil },
		Trees: func(ids []string) (map[string]*parse.Tree, error) {
			boundTrees = filesys.LoadTrees(ids)
			return boundTrees, nil
		},
		Cover: avrender.CoverServices{Parser: legacyTreeProjection().parser, IsImage: func(p string) (bool, error) { return util.IsAssetsImage(p), nil }, Warning: func(e error) { logging.LogWarnf("%s", e) }},
		BlockAttrs: func(ids []string) (map[string]map[string]string, error) {
			if boundTrees != nil {
				return BatchGetBlockAttrsWitTrees(ids, boundTrees), nil
			}
			return BatchGetBlockAttrs(ids), nil
		},
		AutoValues: func(a *av.AttributeView, c av.Collection, ials map[string]map[string]string) error {
			fillAttributeViewAutoGeneratedValues(a, c, ials, depth, cached)
			return nil
		},
		Templates: func(a *av.AttributeView, v *av.View, c av.Collection, ials map[string]map[string]string) error {
			if e := fillAttributeViewTemplateValues(a, v, c, ials); e != nil {
				util.PushErrMsg(fmt.Sprintf(util.Langs[util.Lang][44], util.EscapeHTML(e.Error())), 30000)
			}
			return nil
		},
	}
}
