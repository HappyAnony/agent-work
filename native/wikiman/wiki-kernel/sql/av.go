func fillAttributeViewAutoGeneratedValues(a *av.AttributeView, c av.Collection, ials map[string]map[string]string, depth *int, cached map[string]*av.AttributeView) {
	avrender.FillBasicAutoValues(a, c, ials, time.Now)
	err := avrender.FillRelatedValues(a, c, avrender.RelatedEnvironment{Read: av.ParseAttributeView, Cache: cached, Duration: av.FormatDuration, AllowMissing: true, Fallback: func(a *av.AttributeView, v *av.View, c av.Collection) error {
		return fillAttributeViewTemplateValues(a, v, c, ials)
	}, Render: func(a *av.AttributeView, v *av.View, q string) (av.Viewable, error) {
		return renderView(a, v, q, depth, cached), nil
	}})
	if err != nil {
		logging.LogWarnf("render related AV: %s", err)
	}
}

func GetFurtherCollections(attrView *av.AttributeView, cachedAttrViews map[string]*av.AttributeView) map[string]av.Collection {
	ret, err := avrender.FurtherCollections(context.Background(), attrView, cachedAttrViews, avrender.FurtherEnvironment{Read: av.ParseAttributeView, AllowMissing: true, Render: func(a *av.AttributeView, v *av.View, q string) (av.Viewable, error) { return RenderView(a, v, q), nil }})
	if err != nil {
		logging.LogWarnf("render further AV collections: %s", err)
		return map[string]av.Collection{}
	}
	return ret
}

